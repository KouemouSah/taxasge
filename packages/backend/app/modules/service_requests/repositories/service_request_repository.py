    async def get_request_history(
        self,
        db: asyncpg.Connection,
        request_id: UUID,
        action_types: Optional[List[str]] = None,
        from_date: Optional[str] = None,
        to_date: Optional[str] = None,
        include_system: bool = True,
        include_ocr: bool = True,
        include_assignments: bool = True,
        limit: int = 50,
        offset: int = 0
    ) -> tuple[List[Dict], int]:
        """
        Get full consolidated history timeline for a service request.

        Combines data from:
        - service_request_history (status changes, document uploads, etc.)
        - gemini_processing_logs (OCR processing results)
        - assignments (agent assignments and reassignments)

        Args:
            db: Database connection
            request_id: Service request UUID
            action_types: Filter by action types (e.g., ['status_change', 'document_added'])
            from_date: Filter from date (ISO format)
            to_date: Filter to date (ISO format)
            include_system: Include system-initiated actions (performed_by IS NULL)
            include_ocr: Include OCR processing logs
            include_assignments: Include assignment history
            limit: Max entries to return
            offset: Pagination offset

        Returns:
            Tuple of (list of history entries, total count)
        """
        # Build date conditions for all queries
        date_conditions = []
        date_params: List[Any] = []
        date_param_idx = 2  # $1 is request_id

        if from_date:
            date_conditions.append(f"performed_at >= ${date_param_idx}")
            date_params.append(from_date)
            date_param_idx += 1

        if to_date:
            date_conditions.append(f"performed_at <= ${date_param_idx}")
            date_params.append(to_date)
            date_param_idx += 1

        date_filter = " AND " + " AND ".join(date_conditions) if date_conditions else ""

        # Build action type filter
        action_filter = ""
        if action_types:
            action_filter = f" AND action = ANY(${date_param_idx})"
            date_params.append(action_types)
            date_param_idx += 1

        # System filter
        system_filter = "" if include_system else " AND performed_by IS NOT NULL"

        # Build UNION query for consolidated history
        union_parts = []

        # Part 1: service_request_history
        union_parts.append(f"""
            SELECT
                srh.id::text as id,
                srh.action,
                srh.previous_status,
                srh.new_status,
                srh.details,
                srh.comment,
                srh.performed_at,
                srh.performed_by,
                'history' as source,
                u.id as performer_id,
                COALESCE(u.full_name, u.first_name || ' ' || u.last_name) as performer_name,
                u.email as performer_email,
                u.role as performer_role
            FROM service_request_history srh
            LEFT JOIN users u ON u.id = srh.performed_by
            WHERE srh.service_request_id = $1{date_filter}{action_filter}{system_filter}
        """)

        # Part 2: gemini_processing_logs (OCR)
        if include_ocr:
            # OCR logs don't have action types in the filter
            ocr_date_filter = date_filter.replace("performed_at", "created_at")
            union_parts.append(f"""
                SELECT
                    gpl.id::text as id,
                    CASE
                        WHEN gpl.has_error THEN 'ocr_failed'
                        ELSE 'ocr_completed'
                    END as action,
                    NULL as previous_status,
                    NULL as new_status,
                    jsonb_build_object(
                        'document_code', gpl.document_code,
                        'document_name', gpl.document_name,
                        'extraction_confidence', gpl.extraction_confidence,
                        'risk_level', gpl.risk_level,
                        'risk_score', gpl.risk_score,
                        'processor', gpl.processor,
                        'processing_time_ms', gpl.processing_time_ms,
                        'fields_extracted', gpl.fields_extracted,
                        'fields_missing', gpl.fields_missing,
                        'has_error', gpl.has_error,
                        'error_message', gpl.error_message
                    ) as details,
                    CASE
                        WHEN gpl.has_error THEN gpl.error_message
                        ELSE NULL
                    END as comment,
                    gpl.created_at as performed_at,
                    gpl.user_id as performed_by,
                    'ocr' as source,
                    u.id as performer_id,
                    COALESCE(u.full_name, u.first_name || ' ' || u.last_name) as performer_name,
                    u.email as performer_email,
                    u.role as performer_role
                FROM gemini_processing_logs gpl
                LEFT JOIN users u ON u.id = gpl.user_id
                WHERE gpl.service_request_id = $1{ocr_date_filter}
            """)

        # Part 3: assignments
        if include_assignments:
            assign_date_filter = date_filter.replace("performed_at", "assigned_at")
            union_parts.append(f"""
                SELECT
                    a.id::text as id,
                    CASE
                        WHEN a.reassigned_at IS NOT NULL THEN 'reassigned'
                        ELSE 'assigned'
                    END as action,
                    NULL as previous_status,
                    a.status::text as new_status,
                    jsonb_build_object(
                        'assignment_method', a.assignment_method::text,
                        'priority_level', a.priority_level,
                        'deadline', a.deadline,
                        'reassignment_reason', a.reassignment_reason::text,
                        'reassignment_notes', a.reassignment_notes,
                        'agent_name', COALESCE(agent_user.full_name, agent_user.first_name || ' ' || agent_user.last_name),
                        'reassigned_to_name', COALESCE(reassign_user.full_name, reassign_user.first_name || ' ' || reassign_user.last_name)
                    ) as details,
                    a.notes as comment,
                    COALESCE(a.reassigned_at, a.assigned_at) as performed_at,
                    COALESCE(a.assigned_by_profile_id, a.agent_profile_id) as performed_by,
                    'assignment' as source,
                    assigner.id as performer_id,
                    COALESCE(assigner.full_name, assigner.first_name || ' ' || assigner.last_name) as performer_name,
                    assigner.email as performer_email,
                    assigner.role as performer_role
                FROM assignments a
                LEFT JOIN ministry_agents ma ON ma.id = a.agent_profile_id
                LEFT JOIN users agent_user ON agent_user.id = ma.user_id
                LEFT JOIN ministry_agents ma_reassign ON ma_reassign.id = a.reassigned_to_profile_id
                LEFT JOIN users reassign_user ON reassign_user.id = ma_reassign.user_id
                LEFT JOIN ministry_agents ma_assigner ON ma_assigner.id = COALESCE(a.assigned_by_profile_id, a.agent_profile_id)
                LEFT JOIN users assigner ON assigner.id = ma_assigner.user_id
                WHERE a.item_id = $1 AND a.item_type = 'service_request'{assign_date_filter}
            """)

        union_query = " UNION ALL ".join(union_parts)

        # Count total
        count_query = f"""
            SELECT COUNT(*) as total FROM ({union_query}) consolidated
        """
        all_params = [request_id] + date_params
        count_row = await db.fetchrow(count_query, *all_params)
        total = count_row["total"] if count_row else 0

        # Get paginated entries
        final_query = f"""
            SELECT * FROM ({union_query}) consolidated
            ORDER BY performed_at DESC
            LIMIT ${len(all_params) + 1} OFFSET ${len(all_params) + 2}
        """
        all_params.extend([limit, offset])
        rows = await db.fetch(final_query, *all_params)

        entries = []
        for row in rows:
            entry = {
                "id": row["id"],
                "action": row["action"],
                "previous_status": row["previous_status"],
                "new_status": row["new_status"],
                "details": row["details"] if isinstance(row["details"], dict) else json.loads(row["details"]) if row["details"] else {},
                "comment": row["comment"],
                "performed_at": row["performed_at"].isoformat() if row["performed_at"] else None,
                "source": row["source"],
                "performed_by": None
            }

            # Add performer info if available
            if row["performer_id"]:
                entry["performed_by"] = {
                    "user_id": str(row["performer_id"]),
                    "full_name": row["performer_name"],
                    "email": row["performer_email"],
                    "role": row["performer_role"],
                    "is_system": False
                }
            elif row["performed_by"] is None:
                entry["performed_by"] = {
                    "user_id": None,
                    "full_name": "Sistema",
                    "email": None,
                    "role": "system",
                    "is_system": True
                }

            entries.append(entry)

        return entries, total

    async def get_request_with_history_summary(
        self,
        db: asyncpg.Connection,
        request_id: UUID
    ) -> Optional[Dict]:
        """
        Get service request with history summary statistics.

        Returns request data plus:
        - total_status_changes
        - total_documents
        - total_assignments
        - first_action_at
        - last_action_at
        """
        query = """
            SELECT
                sr.*,
                COALESCE(u.full_name, u.first_name || ' ' || u.last_name, u.email) as citizen_name,
                -- History stats
                (SELECT COUNT(*) FROM service_request_history WHERE service_request_id = sr.id AND action = 'status_change') as total_status_changes,
                (SELECT COUNT(*) FROM service_request_history WHERE service_request_id = sr.id AND action = 'document_added') as total_documents,
                (SELECT COUNT(*) FROM service_request_history WHERE service_request_id = sr.id AND action IN ('assigned', 'reassigned')) as total_assignments,
                (SELECT MIN(performed_at) FROM service_request_history WHERE service_request_id = sr.id) as first_action_at,
                (SELECT MAX(performed_at) FROM service_request_history WHERE service_request_id = sr.id) as last_action_at
            FROM service_requests sr
            JOIN users u ON u.id = sr.user_id
            WHERE sr.id = $1
        """
        row = await db.fetchrow(query, request_id)
        if not row:
            return None

        result = self._row_to_dict(row)
        result["citizen_name"] = row["citizen_name"]
        result["total_status_changes"] = row["total_status_changes"] or 0
        result["total_documents"] = row["total_documents"] or 0
        result["total_assignments"] = row["total_assignments"] or 0
        result["first_action_at"] = row["first_action_at"].isoformat() if row["first_action_at"] else None
        result["last_action_at"] = row["last_action_at"].isoformat() if row["last_action_at"] else None
        return result

    async def get_history_list_for_entity(
        self,
        db: asyncpg.Connection,
        workflow_codes: List[str],
        status_filter: Optional[str] = None,
        limit: int = 20,
        offset: int = 0,
        assigned_to_user_id: Optional[UUID] = None
    ) -> tuple[List[Dict], int]:
        """
        Get list of requests with history summary for an entity.
        Used by the history list page.

        Args:
            db: Database connection
            workflow_codes: List of workflow codes for the entity
            status_filter: Optional status filter
            limit: Max items to return
            offset: Pagination offset
            assigned_to_user_id: If provided, filter by assigned_to (for agent access control)

        Returns:
            Tuple of (list of summary items, total count)
        """
        conditions = ["sr.workflow_code = ANY($1)"]
        params: List[Any] = [workflow_codes]
        param_idx = 2

        if status_filter:
            conditions.append(f"sr.status = ${param_idx}")
            params.append(status_filter)
            param_idx += 1

        # Access control: filter by assigned agent if provided
        if assigned_to_user_id is not None:
            conditions.append(f"sr.assigned_to = ${param_idx}")
            params.append(assigned_to_user_id)
            param_idx += 1

        where_clause = " AND ".join(conditions)

        # Count total
        count_query = f"""
            SELECT COUNT(*) as total
            FROM service_requests sr
            WHERE {where_clause}
        """
        count_row = await db.fetchrow(count_query, *params)
        total = count_row["total"] if count_row else 0

        # Get items with last action info
        params.extend([limit, offset])
        query = f"""
            SELECT
                sr.id,
                sr.reference,
                sr.workflow_code,
                sr.status,
                sr.created_at,
                COALESCE(u.full_name, u.first_name || ' ' || u.last_name, u.email) as citizen_name,
                -- Last action info
                last_history.action as last_action,
                last_history.performed_at as last_action_at,
                COALESCE(last_performer.full_name, last_performer.first_name || ' ' || last_performer.last_name, 'Sistema') as last_performer,
                -- Total actions
                (SELECT COUNT(*) FROM service_request_history WHERE service_request_id = sr.id) as total_actions
            FROM service_requests sr
            JOIN users u ON u.id = sr.user_id
            LEFT JOIN LATERAL (
                SELECT action, performed_at, performed_by
                FROM service_request_history
                WHERE service_request_id = sr.id
                ORDER BY performed_at DESC
                LIMIT 1
            ) last_history ON true
            LEFT JOIN users last_performer ON last_performer.id = last_history.performed_by
            WHERE {where_clause}
            ORDER BY COALESCE(last_history.performed_at, sr.created_at) DESC
            LIMIT ${param_idx} OFFSET ${param_idx + 1}
        """
        rows = await db.fetch(query, *params)

        items = []
        for row in rows:
            days_since = (row["created_at"].date() - row["created_at"].date()).days if row["created_at"] else 0
            last_action_at = row["last_action_at"]
            is_stale = False
            if last_action_at:
                from datetime import datetime, timezone
                now = datetime.now(timezone.utc)
                if last_action_at.tzinfo is None:
                    from datetime import timezone as tz
                    last_action_at = last_action_at.replace(tzinfo=tz.utc)
                is_stale = (now - last_action_at).days >= 7

            items.append({
                "request_id": str(row["id"]),
                "reference": row["reference"] or "",
                "workflow_code": row["workflow_code"],
                "citizen_name": row["citizen_name"] or "N/A",
                "current_status": row["status"],
                "last_action": row["last_action"] or "status_change",
                "last_action_at": row["last_action_at"].isoformat() if row["last_action_at"] else None,
                "last_performer": row["last_performer"],
                "total_actions": row["total_actions"] or 0,
                "days_since_created": days_since,
                "is_stale": is_stale
            })

        return items, total

    def _row_to_dict(self, row: asyncpg.Record) -> Dict:
        """Convert asyncpg Record to dict with proper JSON parsing"""
        if not row:
            return {}
        result = dict(row)
        # Parse JSONB fields
        for field in ["form_data", "extracted_data", "validations", "verification_details"]:
            if field in result and isinstance(result[field], str):
                result[field] = json.loads(result[field])
        return result


